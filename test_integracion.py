def item(producto="buzo", talle="M", cantidad=1, **extra):
    return {
        "producto": producto,
        "talle": talle,
        "cantidad": cantidad,
        **extra,
    }


def contar(ruta, tabla):
    assert tabla in ("pedidos", "items")
    otra = pedidos.conectar(ruta)
    try:
        return otra.execute(f"SELECT COUNT(*) FROM {tabla}").fetchone()[0]
    finally:
        otra.close()
